#!/usr/bin/env python3
"""Export generated trace figures as PGFPlots/TikZ include files.

The output .tex files are intentionally include fragments:

  \\input{figs/tikz/<name>.tex}

The parent LaTeX document should load pgfplots and the groupplots library.
Data are emitted as small whitespace-separated .dat tables next to the TeX.
"""

import argparse
import csv
from collections import defaultdict
from pathlib import Path


KINDS = ("WKV", "WML", "WIX")
KIND_COLORS = {"WKV": "kvblue", "WML": "memgreen", "WIX": "ixorange"}
KIND_LABELS = {
    "WKV": "KV blob append",
    "WML": "memory-log append",
    "WIX": "vector-index update",
}
MARKS = ["*", "square*", "triangle*", "diamond*", "pentagon*", "otimes*", "star", "triangle", "square"]


def read_csv(path):
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def fnum(v):
    return f"{float(v):.6f}".rstrip("0").rstrip(".")


def tex_escape(s):
    return str(s).replace("_", r"\_")


def write_dat(path, pairs):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as f:
        f.write("x y\n")
        for x, y in pairs:
            f.write(f"{fnum(x)} {fnum(y)}\n")


def rel_data_path(data_path, tex_path):
    return data_path.relative_to(tex_path.parent).as_posix()


def color_defs():
    return "\n".join(
        [
            r"\definecolor{kvblue}{HTML}{2471A3}",
            r"\definecolor{memgreen}{HTML}{2CA25F}",
            r"\definecolor{ixorange}{HTML}{D95F0E}",
            r"\pgfplotsset{compat=1.18}",
        ]
    )


def addplot_table(data_path, tex_path, color, mark="*", size="1.7pt", opacity="0.65", extra=""):
    rel = rel_data_path(data_path, tex_path)
    return (
        rf"\addplot+[only marks, mark={mark}, mark size={size}, color={color}, "
        rf"mark options={{fill={color}, draw={color}}}, opacity={opacity}, forget plot{extra}] "
        rf"table[x=x,y=y] {{{rel}}};"
    )


def add_write_type_legend():
    lines = []
    for kind in KINDS:
        color = KIND_COLORS[kind]
        lines.append(
            rf"\addlegendimage{{only marks, mark=*, mark options={{fill={color}, draw={color}}}, color={color}}}"
        )
        lines.append(rf"\addlegendentry{{{KIND_LABELS[kind]}}}")
    return lines


def add_session_legend(sids):
    lines = []
    for i, sid in enumerate(sids):
        mark = MARKS[i % len(MARKS)]
        lines.append(rf"\addlegendimage{{only marks, mark={mark}, mark options={{fill=black, draw=black}}, color=black}}")
        lines.append(rf"\addlegendentry{{sid {sid}}}")
    lines.append(r"\addlegendimage{only marks, mark=*, mark options={fill=black, draw=black}, color=black}")
    lines.append(r"\addlegendentry{arrival: filled session marker}")
    lines.append(r"\addlegendimage{only marks, mark=*, mark options={fill=white, draw=black}, color=black}")
    lines.append(r"\addlegendentry{DEL/end: open session marker}")
    return lines


def axis_common():
    return "\n".join(
        [
            r"width=0.98\linewidth,",
            r"height=0.29\linewidth,",
            r"tick label style={font=\scriptsize},",
            r"label style={font=\small},",
            r"title style={font=\small},",
            r"legend style={font=\scriptsize, draw=none, fill=none, at={(0.99,0.99)}, anchor=north east},",
            r"grid=both,",
            r"grid style={black!12},",
        ]
    )


def export_absolute(csv_path, out_dir, prefix, title):
    rows = read_csv(csv_path)
    if not rows:
        return None
    data_dir = out_dir / "data"
    tex_path = out_dir / f"{prefix}.tex"
    sids = sorted({int(r["sid"]) for r in rows})
    sid_to_mark = {sid: MARKS[i % len(MARKS)] for i, sid in enumerate(sids)}
    sid_to_y = {sid: len(sids) - 1 - i for i, sid in enumerate(sids)}

    starts = {sid: float(next(r for r in rows if int(r["sid"]) == sid)["arrival_s"]) for sid in sids}
    ends = {sid: float(next(r for r in rows if int(r["sid"]) == sid)["end_s"]) for sid in sids}
    ended = {sid: int(next(r for r in rows if int(r["sid"]) == sid)["has_del"]) for sid in sids}
    x0 = min(starts.values())
    x1 = max(ends.values())
    pad = max(5.0, 0.02 * (x1 - x0))
    xmin, xmax = x0 - pad, x1 + pad

    tex = [
        "% Auto-generated by scripts/export_tikz_figures.py",
        "% Requires: \\usepackage{pgfplots}; \\usepgfplotslibrary{groupplots}",
        color_defs(),
        r"\begin{tikzpicture}",
        r"\begin{groupplot}[",
        r"group style={group size=1 by 3, vertical sep=0.75cm},",
        axis_common(),
        r"]",
        rf"\nextgroupplot[title={{{tex_escape(title)}}}, ylabel={{write size (KiB)}}, ymode=log, xmin={fnum(xmin)}, xmax={fnum(xmax)}, legend columns=3]",
    ]

    for sid in sids:
        mark = sid_to_mark[sid]
        for kind in KINDS:
            sub = [r for r in rows if int(r["sid"]) == sid and r["kind"] == kind]
            if not sub:
                continue
            p = data_dir / f"{prefix}_sid{sid}_{kind}_size.dat"
            write_dat(p, [(r["time_s"], r["len_kib"]) for r in sub])
            tex.append(addplot_table(p, tex_path, KIND_COLORS[kind], mark=mark, opacity="0.66"))

    tex.extend(add_write_type_legend())
    tex.extend(add_session_legend(sids))

    tex.append(rf"\nextgroupplot[ylabel={{logical offset (MiB)}}, xmin={fnum(xmin)}, xmax={fnum(xmax)}]")
    for sid in sids:
        mark = sid_to_mark[sid]
        for kind in KINDS:
            sub = [r for r in rows if int(r["sid"]) == sid and r["kind"] == kind]
            if not sub:
                continue
            p = data_dir / f"{prefix}_sid{sid}_{kind}_offset.dat"
            write_dat(p, [(r["time_s"], r["off_mib"]) for r in sub])
            tex.append(addplot_table(p, tex_path, KIND_COLORS[kind], mark=mark, opacity="0.60"))

    yticks = ",".join(str(sid_to_y[sid]) for sid in sids)
    yticklabels = ",".join(f"sid {sid}" for sid in sids)
    tex.append(
        rf"\nextgroupplot[ylabel={{session}}, xlabel={{absolute trace time (s)}}, xmin={fnum(xmin)}, xmax={fnum(xmax)}, "
        rf"ymin=-0.6, ymax={len(sids)-0.4}, ytick={{{yticks}}}, yticklabels={{{yticklabels}}}, grid=major]"
    )
    for sid in sids:
        y = sid_to_y[sid]
        mark = sid_to_mark[sid]
        tex.append(rf"\draw[black!50, line width=0.8pt] (axis cs:{fnum(starts[sid])},{y}) -- (axis cs:{fnum(ends[sid])},{y});")
        tex.append(
            rf"\addplot+[only marks, mark={mark}, mark size=2.4pt, color=black, "
            rf"mark options={{fill=black, draw=black}}, forget plot] coordinates {{({fnum(starts[sid])},{y})}};"
        )
        fill = "white" if ended[sid] else "black!10"
        tex.append(
            rf"\addplot+[only marks, mark={mark}, mark size=2.5pt, color=black, "
            rf"mark options={{fill={fill}, draw=black}}, forget plot] coordinates {{({fnum(ends[sid])},{y})}};"
        )

    for sid in sids:
        mark = sid_to_mark[sid]
        y = sid_to_y[sid]
        for kind in KINDS:
            sub = [r for r in rows if int(r["sid"]) == sid and r["kind"] == kind]
            if not sub:
                continue
            p = data_dir / f"{prefix}_sid{sid}_{kind}_life.dat"
            write_dat(p, [(r["time_s"], y) for r in sub])
            tex.append(addplot_table(p, tex_path, KIND_COLORS[kind], mark=mark, size="1.4pt", opacity="0.45"))

    tex.extend([r"\end{groupplot}", r"\end{tikzpicture}", ""])
    tex_path.write_text("\n".join(tex))
    return tex_path


def export_one_session(csv_path, out_dir, prefix, title):
    rows = read_csv(csv_path)
    if not rows:
        return None
    data_dir = out_dir / "data"
    tex_path = out_dir / f"{prefix}.tex"
    xmax = max(float(r["time_s"]) for r in rows)

    tex = [
        "% Auto-generated by scripts/export_tikz_figures.py",
        "% Requires: \\usepackage{pgfplots}; \\usepgfplotslibrary{groupplots}",
        color_defs(),
        r"\begin{tikzpicture}",
        r"\begin{groupplot}[",
        r"group style={group size=1 by 2, vertical sep=0.75cm},",
        axis_common(),
        r"]",
        rf"\nextgroupplot[title={{{tex_escape(title)}}}, ylabel={{write size (KiB)}}, ymode=log, xmin=0, xmax={fnum(xmax)}, legend columns=3]",
    ]
    for kind in KINDS:
        sub = [r for r in rows if r["kind"] == kind]
        if not sub:
            continue
        p = data_dir / f"{prefix}_{kind}_size.dat"
        write_dat(p, [(r["time_s"], r["len_kib"]) for r in sub])
        tex.append(addplot_table(p, tex_path, KIND_COLORS[kind], mark="*", opacity="0.75"))
    tex.extend(add_write_type_legend())

    tex.append(rf"\nextgroupplot[ylabel={{logical offset (MiB)}}, xlabel={{time since session arrival (s)}}, xmin=0, xmax={fnum(xmax)}]")
    wkv_line = None
    for kind in KINDS:
        sub = [r for r in rows if r["kind"] == kind]
        if not sub:
            continue
        p = data_dir / f"{prefix}_{kind}_offset.dat"
        write_dat(p, [(r["time_s"], r["off_mib"]) for r in sub])
        tex.append(addplot_table(p, tex_path, KIND_COLORS[kind], mark="*", opacity="0.68"))
        if kind == "WKV":
            wkv_line = p
    if wkv_line:
        tex.append(
            rf"\addplot+[mark=none, color=kvblue, opacity=0.45, forget plot] "
            rf"table[x=x,y=y] {{{rel_data_path(wkv_line, tex_path)}}};"
        )
    tex.extend([r"\end{groupplot}", r"\end{tikzpicture}", ""])
    tex_path.write_text("\n".join(tex))
    return tex_path


def export_aligned(csv_path, out_dir, prefix):
    rows = read_csv(csv_path)
    if not rows:
        return None
    data_dir = out_dir / "data"
    tex_path = out_dir / f"{prefix}.tex"
    sids = sorted({int(r["sid"]) for r in rows})
    sid_to_y = {sid: i for i, sid in enumerate(sids)}
    lifetimes = {sid: float(next(r for r in rows if int(r["sid"]) == sid)["session_lifetime_s"]) for sid in sids}
    ended = {sid: int(next(r for r in rows if int(r["sid"]) == sid)["session_has_del"]) for sid in sids}
    xmax = max(lifetimes.values())

    tex = [
        "% Auto-generated by scripts/export_tikz_figures.py",
        "% Requires: \\usepackage{pgfplots}; \\usepgfplotslibrary{groupplots}",
        color_defs(),
        r"\begin{tikzpicture}",
        r"\begin{groupplot}[",
        r"group style={group size=1 by 3, vertical sep=0.75cm},",
        axis_common(),
        r"]",
        rf"\nextgroupplot[title={{All sessions aligned at arrival: write size}}, ylabel={{write size (KiB)}}, ymode=log, xmin=0, xmax={fnum(xmax)}, legend columns=3]",
    ]
    for kind in KINDS:
        sub = [r for r in rows if r["kind"] == kind]
        p = data_dir / f"{prefix}_{kind}_size.dat"
        write_dat(p, [(r["time_s"], r["len_kib"]) for r in sub])
        tex.append(addplot_table(p, tex_path, KIND_COLORS[kind], mark="*", size="0.7pt", opacity="0.35"))
    tex.extend(add_write_type_legend())

    tex.append(rf"\nextgroupplot[title={{All sessions aligned at arrival: write offset}}, ylabel={{logical offset (MiB)}}, xmin=0, xmax={fnum(xmax)}]")
    for kind in KINDS:
        sub = [r for r in rows if r["kind"] == kind]
        p = data_dir / f"{prefix}_{kind}_offset.dat"
        write_dat(p, [(r["time_s"], r["off_mib"]) for r in sub])
        tex.append(addplot_table(p, tex_path, KIND_COLORS[kind], mark="*", size="0.7pt", opacity="0.30"))

    tex.append(
        rf"\nextgroupplot[title={{Session lifetimes}}, ylabel={{sessions ordered by arrival}}, xlabel={{time since session arrival (s)}}, "
        rf"xmin=0, xmax={fnum(xmax)}, ymin=-2, ymax={len(sids)+2}, ytick=\empty, grid=major]"
    )
    for sid in sids:
        y = sid_to_y[sid]
        tex.append(rf"\draw[black!35, line width=0.25pt] (axis cs:0,{y}) -- (axis cs:{fnum(lifetimes[sid])},{y});")
        if ended[sid]:
            tex.append(
                rf"\addplot+[only marks, mark=|, mark size=0.8pt, color=black!35, forget plot] "
                rf"coordinates {{({fnum(lifetimes[sid])},{y})}};"
            )
    for kind in KINDS:
        sub = [r for r in rows if r["kind"] == kind]
        p = data_dir / f"{prefix}_{kind}_life.dat"
        write_dat(p, [(r["time_s"], sid_to_y[int(r["sid"])]) for r in sub])
        tex.append(addplot_table(p, tex_path, KIND_COLORS[kind], mark="*", size="0.45pt", opacity="0.22"))

    tex.extend([r"\end{groupplot}", r"\end{tikzpicture}", ""])
    tex_path.write_text("\n".join(tex))
    return tex_path


def write_readme(out_dir, outputs):
    lines = [
        "# TikZ figure exports",
        "",
        "These files are PGFPlots/TikZ include fragments generated from the CSV data behind the PNG figures.",
        "",
        "Add this to the LaTeX preamble:",
        "",
        "```tex",
        r"\usepackage{pgfplots}",
        r"\usepgfplotslibrary{groupplots}",
        r"\pgfplotsset{compat=1.18}",
        "```",
        "",
        "Then include a figure with:",
        "",
        "```tex",
        r"\begin{figure}",
        r"  \centering",
        r"  \input{figs/tikz/first5_sessions_absolute_write_timeline.tex}",
        r"  \caption{...}",
        r"\end{figure}",
        "```",
        "",
        "Generated files:",
    ]
    for p in outputs:
        lines.append(f"- `{p.relative_to(out_dir.parent).as_posix()}`")
    lines.extend(
        [
            "",
            "Note: `session_aligned_write_timeline.tex` uses exact external data for all sessions and can be slower to compile than the first-five/session-only figures. Use PGFPlots externalization if it becomes a bottleneck.",
        ]
    )
    lines.append("")
    out_dir.joinpath("README.md").write_text("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fig-dir", type=Path, default=Path("../figs"))
    ap.add_argument("--out-dir", type=Path, default=Path("../figs/tikz"))
    args = ap.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)
    outputs = []

    jobs = [
        (
            "absolute",
            args.fig_dir / "3.csv",
            "3",
            "3",
        )
    ]

    for kind, csv_path, prefix, title in jobs:
        if not csv_path.exists():
            continue
        if kind == "absolute":
            out = export_absolute(csv_path, args.out_dir, prefix, title)
        elif kind == "single":
            out = export_one_session(csv_path, args.out_dir, prefix, title)
        else:
            out = export_aligned(csv_path, args.out_dir, prefix)
        if out:
            outputs.append(out)
            print(f"wrote {out}")

    write_readme(args.out_dir, outputs)
    print(f"wrote {args.out_dir / 'README.md'}")


if __name__ == "__main__":
    main()
